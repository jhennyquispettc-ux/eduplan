#!/bin/sh
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE USER ${AUTH_DB_USER} WITH PASSWORD '${AUTH_DB_PASSWORD}';
  CREATE DATABASE ${AUTH_DB_NAME} OWNER ${AUTH_DB_USER};
  REVOKE ALL ON DATABASE ${AUTH_DB_NAME} FROM PUBLIC;

  CREATE USER ${COURSES_DB_USER} WITH PASSWORD '${COURSES_DB_PASSWORD}';
  CREATE DATABASE ${COURSES_DB_NAME} OWNER ${COURSES_DB_USER};
  REVOKE ALL ON DATABASE ${COURSES_DB_NAME} FROM PUBLIC;
EOSQL
